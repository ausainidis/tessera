// Dependency licence check. Run before every release: npm run licenses
//
// Checks every package that ends up in the distributed application:
//  - runtime dependencies (shipped in node_modules inside the app), and
//  - packages bundled into dist/editor or dist/runtime by Vite (React etc.).
// Fails if any licence is not on the allow-list, and writes THIRD_PARTY_NOTICES.md.
// Electron/Chromium licences are shipped by Electron itself (LICENSE, LICENSES.chromium.html).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense', 'Python-2.0']);
// Packages bundled into the editor/runtime builds (devDependencies that still ship).
const BUNDLED = ['react', 'react-dom', 'scheduler'];

function collect(name, seen, from = ROOT) {
  if (seen.has(name)) return;
  let dir = path.join(from, 'node_modules', name);
  if (!fs.existsSync(dir)) dir = path.join(ROOT, 'node_modules', name);
  if (!fs.existsSync(dir)) return;
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  seen.set(name, { dir, pkg });
  for (const dep of Object.keys(pkg.dependencies || {})) collect(dep, seen, dir);
}

const root = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const seen = new Map();
for (const dep of [...Object.keys(root.dependencies || {}), ...BUNDLED]) collect(dep, seen);

const rows = [];
const problems = [];
for (const [name, { dir, pkg }] of [...seen].sort(([a], [b]) => a.localeCompare(b))) {
  const lic = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type || (pkg.licenses || []).map((l) => l.type).join(' OR ') || 'UNKNOWN';
  const ids = lic.replace(/[()]/g, '').split(/\s+(?:OR|AND)\s+/);
  const ok = lic.includes(' AND ') ? ids.every((i) => ALLOWED.has(i)) : ids.some((i) => ALLOWED.has(i));
  if (!ok) problems.push(`${name}@${pkg.version}: ${lic}`);
  const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  rows.push({ name, version: pkg.version, license: lic, text: file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : null, repo: typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url || '' });
}

let electronVersion = '';
try { electronVersion = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', 'electron', 'package.json'), 'utf8')).version; } catch { /* not installed */ }

const md = [
  '# Third-party notices',
  '',
  'Tessera is licensed under the Apache License 2.0 (see LICENSE). It includes the following',
  'third-party software. This file is generated by `npm run licenses`; do not edit by hand.',
  '',
  `Electron ${electronVersion} (MIT) and Chromium are distributed with their own licence files`,
  '(`LICENSE` and `LICENSES.chromium.html` in the application folder).',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
  ...rows.flatMap((r) => [`## ${r.name} ${r.version}`, '', r.repo ? `Source: ${r.repo.replace(/^git\+/, '')}` : '', '', '```', r.text || `Licence: ${r.license} (no licence file in package)`, '```', '']),
].join('\n');
fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), md);

console.log(`Checked ${rows.length} shipped packages.`);
for (const r of rows) console.log(`  ${r.license.padEnd(14)} ${r.name}@${r.version}`);
if (problems.length) {
  console.error(`\nLicences not on the allow-list:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.log('\nAll shipped dependency licences are on the allow-list. Wrote THIRD_PARTY_NOTICES.md.');

// Development-only tools are not shipped, but are listed for transparency.
console.log(`Development tools (not distributed): ${Object.keys(root.devDependencies || {}).filter((d) => !BUNDLED.includes(d)).join(', ')}`);
